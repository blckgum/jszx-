# 本文件属于原有分类学习模块；校园道路检测与跟踪使用 detection/、tracking/ 入口。

"""
config.py —— 全局配置

所有"可能要改的数字"都集中放这里，不要散落在各个脚本里。
这是工程习惯：以后想调参数，只改一个文件。

★ 重要观念：这些数字叫"超参数"(hyperparameter)。
   不是模型学出来的，是**你手工设定**的。
   调参 = 调这些数字。模型自己学出来的叫"参数"(parameter)，比如卷积核里的值。
"""

from pathlib import Path

# ============================================================
# 路径
# ============================================================

# Path(__file__) 是当前文件路径，.parent 是它所在的目录，也就是项目根目录。
# 用这种方式写路径，不管你从哪里运行脚本，路径都是对的。
ROOT = Path(__file__).parent

DATA_DIR = ROOT / "data"        # 原始数据集存放处
RUNS_DIR = ROOT / "runs"        # 训练输出（日志、权重、曲线图）
CKPT_DIR = ROOT / "checkpoints" # 模型权重

# 训练产物（会自动创建）
BEST_MODEL_PATH = CKPT_DIR / "best.pt"   # 验证集表现最好的模型 ← 最终要用的
LAST_MODEL_PATH = CKPT_DIR / "last.pt"   # 最后一轮的模型（用来接着训练）


# ============================================================
# 数据集
# ============================================================

# 当前用 CIFAR-10（10 类小图，能自动下载，适合练手）
# ★ 等你想好课题了，改这里就行
DATASET_NAME = "CIFAR10"

CIFAR10_CLASSES = [
    "airplane",   # 0 飞机
    "automobile", # 1 汽车
    "bird",       # 2 鸟
    "cat",        # 3 猫
    "deer",       # 4 鹿
    "dog",        # 5 狗
    "frog",       # 6 青蛙
    "horse",      # 7 马
    "ship",       # 8 船
    "truck",      # 9 卡车
]

NUM_CLASSES = len(CIFAR10_CLASSES)  # 输出层神经元个数 = 类别数
IMAGE_SIZE = 32                     # CIFAR-10 的图片是 32x32
IN_CHANNELS = 3                     # RGB 三通道

# ★ 标准化用的均值和标准差
#   为什么要标准化？让数据分布接近"均值0、标准差1"，
#   这样每一层的输入尺度稳定，梯度不会爆炸或消失，训练更稳更快。
#   这三个数字是统计 CIFAR-10 全部图片算出来的，直接抄即可。
CIFAR10_MEAN = (0.4914, 0.4822, 0.4465)
CIFAR10_STD = (0.2470, 0.2435, 0.2616)


# ============================================================
# 训练超参数
# ============================================================

BATCH_SIZE = 128        # 一个批次多少张图。
                        # 大 → 更稳但费显存；小 → 有正则化效果但抖动大。
                        # 8GB 显存跑 32x32 小图，128 很轻松；换大图要调小。

EPOCHS = 30             # 整个数据集过多少遍
LEARNING_RATE = 1e-3    # 学习率，最重要的超参数。步子迈多大。
WEIGHT_DECAY = 1e-4     # AdamW 中为解耦权重衰减，区别于直接在损失中加 L2 项
MOMENTUM = 0.9          # SGD 的动量：让更新方向更平滑，像小球滚下山有惯性
NUM_WORKERS = 0         # 读数据的子进程数。
                        # 使用 0 可减少 Windows 进程启动差异，适合先跑通教学流程。
                        # Windows 也支持多进程，需正确的主入口保护；增加前应实测。
SEED = 42               # 固定随机源以减少差异，跨设备和版本不保证逐位复现

# 早停：验证准确率连续未提升的轮数阈值；还需本轮 loss 高于此前最小值
# 实际组合条件见 train.py，不是单独按 loss 计数
EARLY_STOP_PATIENCE = 10

# 学习率调度：用余弦退火
# 前期 lr 大 → 快速下降；后期 lr 小 → 精细调整
USE_SCHEDULER = True


# ============================================================
# 数据增强强度（只在训练时生效，验证/测试时不加！）
# ============================================================

# ★ 为什么验证集不能加增强？
#   增强会改变图片内容（翻转、裁剪）。评估必须要用"原始分布"的数据，
#   否则指标就失去意义了。这是新手常犯的错误。

AUG_HORIZONTAL_FLIP_P = 0.5     # 水平翻转的概率（猫翻转还是猫）
AUG_CROP_SIZE = 32              # 随机裁剪后的大小
AUG_CROP_PADDING = 4            # 裁剪前先在四周补 4 像素，再随机裁回 32x32
AUG_ROTATION_DEGREES = 15       # 随机旋转 ±15 度
AUG_COLOR_JITTER = 0.2          # 亮度/对比度/饱和度随机抖动幅度


# ============================================================
# 推理
# ============================================================

TOP_K = 3               # 显示置信度最高的前 K 个类别
CONF_THRESHOLD = 0.5    # 分类文件夹预测的低分提示阈值，不是检测入口的 conf


# ============================================================
# 模型
# ============================================================

MODEL_NAME = "SimpleCNN"    # 可选 "SimpleCNN" / "ResNet18"（迁移学习）

# 是否用迁移学习（用 ImageNet 预训练权重）
# ★ 强烈建议等 SimpleCNN 跑通后再试，能立刻看到效果提升
USE_PRETRAINED = False


if __name__ == "__main__":
    # 直接运行本文件可以把配置打印出来检查
    from common import banner

    banner("当前配置")
    for k, v in sorted(globals().items()):
        # 跳过模块、函数、以 _ 开头的私有变量
        if k.isupper() and not k.startswith("_"):
            print(f"{k:28s} = {v}")
